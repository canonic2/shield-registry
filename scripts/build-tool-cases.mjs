export const destination = name => new URL(`../packs/canonic/${name}/0.1.0/`, import.meta.url);

export function casesFor(name) {
  const {argv, mcp} = scenarios[name];
  // An MCP row may name its own transport; otherwise the pack's defaults launch the server.
  const connection = (transport = {type: 'defaults', pack: `canonic/${name}`, integration: name}) => ({[name]: {transport,
    agents: {codex: name}, packs: {[`canonic/${name}`]: name}}});
  return [
    ...argv.flatMap(([id, args, expected]) => profiles.map((profile, i) => ({name: `${id}-${profile}`, profile, argv: args, expected: expected[i]}))),
    ...mcp.flatMap(([id, tool, args, expected, transport]) => profiles.map((profile, i) => ({name: `mcp-${id}-${profile}`, profile, expected: expected[i],
      mcp: connection(transport), input: {kind: 'mcp', server: name, tool, arguments: args, original_input: {}}}))),
  ];
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  for (const name of Object.keys(scenarios))
    await writeFile(new URL('cases.json', destination(name)), JSON.stringify({schema_version: 1, cases: casesFor(name)}, null, 2) + '\n');
}
