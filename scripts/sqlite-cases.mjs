export function sqliteCases() {
  return {schema_version: 1, cases: ['loose', 'recommended', 'strict'].flatMap((profile, index) => [
    ...cli.map(([name, argv, expected]) => ({name: `${name}-${profile}`, profile, argv, expected: expected[index]})),
    {name: `stdin-script-${profile}`, profile, input: {kind: 'shell', dialect: 'posix', dialect_version: null,
      source: "printf 'SELECT 1;' | sqlite3 ./example.db", original_input: {}}, expected: review[index]},
    {name: `redirect-script-${profile}`, profile, input: {kind: 'shell', dialect: 'posix', dialect_version: null,
      source: 'sqlite3 ./example.db < example.sql', original_input: {}}, expected: review[index]},
    {name: `unclassified-mcp-${profile}`, profile, input: {kind: 'mcp', server: 'sqlite', tool: 'query',
      arguments: {sql: 'SELECT 1;'}, original_input: {}}, expected: 'ask'},
  ])};
}
